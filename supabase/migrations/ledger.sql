create table if not exists settings (
  id integer primary key check (id = 1),
  wallet text not null default ''
);

insert into settings (id, wallet)
select 1, ''
where not exists (select 1 from settings where id = 1);

create table if not exists sync_years (
  year integer primary key,
  newest_block_time bigint,
  tx_count integer not null,
  updated_at bigint not null
);

create table if not exists transactions (
  signature text primary key,
  slot bigint not null,
  tx_index integer not null,
  block_time bigint not null,
  raw_json text not null
);

create index if not exists idx_tx_time on transactions (block_time, slot, tx_index);

create table if not exists pools (
  id text primary key,
  mint0 text,
  mint1 text,
  decimals0 integer,
  decimals1 integer,
  symbol0 text,
  symbol1 text,
  sqrt_price_x64 text,
  tick_current integer,
  updated_at bigint not null
);

create table if not exists positions (
  nft_mint text primary key,
  pool_id text,
  tick_lower integer,
  tick_upper integer,
  opened_at bigint,
  closed_at bigint,
  status text not null,
  liquidity text not null default '0',
  amount0 text,
  amount1 text,
  fee_owed0 text not null default '0',
  fee_owed1 text not null default '0',
  in_range boolean,
  updated_at bigint not null
);

create table if not exists events (
  id bigint generated by default as identity primary key,
  signature text not null,
  slot bigint not null,
  tx_index integer not null,
  event_index integer not null,
  block_time bigint not null,
  nft_mint text not null,
  pool_id text,
  kind text not null,
  liquidity text not null,
  amount0 text not null,
  amount1 text not null,
  fee0 text not null,
  fee1 text not null,
  sqrt_price_x64 text,
  mint0 text,
  mint1 text,
  tick_lower integer,
  tick_upper integer,
  unique (signature, event_index)
);

create table if not exists lots (
  id integer primary key,
  nft_mint text not null,
  mint text not null,
  kind text not null,
  amount text not null,
  remaining text not null,
  cost text,
  cost_remaining text,
  block_time bigint not null,
  slot bigint not null,
  tx_index integer not null,
  event_index integer not null,
  signature text not null
);

create table if not exists sales (
  id integer primary key,
  signature text not null,
  block_time bigint not null,
  slot bigint not null,
  tx_index integer not null,
  mint text not null,
  amount text not null,
  usdc text not null,
  router text
);

create table if not exists sale_matches (
  id bigint generated by default as identity primary key,
  sale_id integer not null,
  lot_id integer not null,
  nft_mint text not null,
  mint text not null,
  lot_kind text not null,
  amount text not null,
  usdc text not null,
  cost text,
  block_time bigint not null,
  signature text not null
);

create table if not exists cash_flows (
  id bigint generated by default as identity primary key,
  nft_mint text not null,
  signature text not null,
  block_time bigint not null,
  slot bigint not null,
  tx_index integer not null,
  kind text not null,
  amount text not null,
  cost text
);

create table if not exists position_costs (
  nft_mint text primary key,
  cost text
);

